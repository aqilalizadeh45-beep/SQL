--TASK1
SELECT MANAGER_ID,
       COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NOT NULL
GROUP BY MANAGER_ID
ORDER BY ISCI_SAYI DESC;
    

--TASK2
SELECT COUNTRY_ID,
       COUNT(LOCATION_ID) AS OFIS_SAYI
FROM HR.LOCATIONS
GROUP BY COUNTRY_ID
ORDER BY OFIS_SAYI DESC;


--TASK3
SELECT E.FIRST_NAME,E.LAST_NAME,E.JOB_ID,D.JOB_ID AS JOB_TITLE
FROM HR.EMPLOYEES E
JOIN HR.JOBS D
ON E.JOB_ID=D.JOB_ID

--TASK4
SELECT DEPARTMENT_ID,
       ROUND(AVG(SALARY),2) AS ORTA_MAAS
FROM HR.EMPLOYEES 
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
HAVING ORTA_MAAS>8000;

--TASK5
SELECT DEPARTMENT_ID,
       COUNT(SALARY>=3000) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING ISCI_SAYI>3;


--TASK6
SELECT 
    j.JOB_TITLE, 
    COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.JOBS J 
ON E.JOB_ID = J.JOB_ID
GROUP BY J.JOB_TITLE
ORDER BY ISCI_SAYI DESC;

--TASK7
SELECT L.CITY,L.COUNTRY_ID
FROM HR.LOCATIONS L
LEFT JOIN HR.DEPARTMENTS D
ON L.LOCATION_ID=D.LOCATION_ID 
WHERE D.DEPARTMENT_ID IS NULL

--TASK8
SELECT 
    J.JOB_TITLE, 
    AVG(E.SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J 
ON E.JOB_ID = J.JOB_ID 
GROUP BY J.JOB_TITLE
HAVING AVG(E.SALARY) > 10000;
