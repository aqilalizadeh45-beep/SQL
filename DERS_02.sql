--TASK9
SELECT 
    L.CITY, 
    COUNT(*) AS ISCI_SAYI, 
    ROUND(AVG(E.SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.LOCATIONS L 
ON D.LOCATION_ID = L.LOCATION_ID
GROUP BY L.CITY
HAVING COUNT(*) > 5
ORDER BY ISCI_SAYI DESC;

