--TASK6
SELECT J.JOB_TITLE,
       ROUND(AVG(SALARY),2) AS ORTA_MAAS
FROM HR.JOBS J
JOIN HR.EMPLOYEES E
ON E.JOB_ID=J.JOB_ID
GROUP BY JOB_TITLE 
HAVING AVG(SALARY)>6000 AND AVG(SALARY)<12000

--TASK7
SELECT JOB_TITLE
FROM HR.JOBS J
LEFT JOIN HR.EMPLOYEES E
ON E.JOB_ID=J.JOB_ID
WHERE E.EMPLOYEE_ID IS NULL

--TASK8
SELECT D.DEPARTMENT_NAME, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D 
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME;
HAVING ISCI_SAYI > 4
