--TASK1
SELECT FIRST_NAME,LAST_NAME,SALARY,
    CASE WHEN SALARY<6000 THEN 'ASAGI'
    WHEN SALARY>=6000 AND SALARY<=12000 THEN 'ORTA'
    ELSE 'YUKSEK'
    END AS MAAS_SEVIYYESI
FROM HR.EMPLOYEES;

--TASK2
SELECT FIRST_NAME,JOB_ID,
       CASE JOB_ID
       WHEN 'IT_PROG' THEN 'PROQRAMCI'
       WHEN 'SA_REP'  THEN 'SATIS NUMAYENDESI'
       WHEN 'ST_CLERK' THEN 'ANBAR ISCISI'
       ELSE 'DIGER'
       END AS VEZIFE
FROM HR.EMPLOYEES;

--TASK3
--CASE ILE
SELECT FIRST_NAME,COMMISSION_PCT,
       CASE WHEN COMMISSION_PCT IS NULL THEN 'KOMISSIYA YOXDUR'
       WHEN COMMISSION_PCT IS NOT NULL THEN 'KOMISSIYA VAR'
       END AS KOMISSIYA_STATUSU
FROM HR.EMPLOYEES;
--NVL2 ILE
SELECT FIRST_NAME,COMMISSION_PCT,
       NVL2(COMMISSION_PCT,'KOMISSIYA VAR','KOMISSIYA YOXDUR') AS KOMISSIYA_STATUSU
FROM HR.EMPLOYEES;

--TASK4
SELECT CITY,COUNTRY_ID,
       CASE WHEN COUNTRY_ID IN ('US','CA','MX','BR') THEN 'AMERIKA'
       WHEN COUNTRY_ID IN ('UK','DE','IT','NL','CH') THEN 'AVROPA'
       WHEN COUNTRY_ID IN ('JP','CN','IN','SG') THEN 'ASIYA'
       ELSE 'DIGER'
       END AS QITE
FROM HR.LOCATIONS;

--TASK5
SELECT FIRST_NAME,DEPARTMENT_ID,SALARY,
       CASE WHEN DEPARTMENT_ID=80 THEN SALARY*1.1
       WHEN DEPARTMENT_ID=60 THEN SALARY*1.15
       ELSE SALARY*1.05
       END AS BONUS
FROM HR.EMPLOYEES
ORDER BY BONUS DESC;

--TASK6
SELECT FIRST_NAME, SALARY,
       CASE
           WHEN SALARY > 5000 AND SALARY<15000  THEN 'Orta'
           WHEN SALARY > 15000  THEN 'Yuksek'
           ELSE 'ASAGI'
       END AS Seviyye
FROM HR.EMPLOYEES;
