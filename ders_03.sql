--TASK7
SELECT FIRST_NAME,JOB_ID,MANAGER_ID,
       CASE WHEN MANAGER_ID IS NULL THEN 'Direktor'
       WHEN MANAGER_ID=100 THEN 'Direktorun komandasi'
       WHEN JOB_ID LIKE '%MAN' OR JOB_ID LIKE '%MGR' THEN 'Menecer'
       ELSE 'Isci'
       END AS ROL
FROM HR.EMPLOYEES;

--TASK8
SELECT FIRST_NAME,SALARY,COMMISSION_PCT,
       NVL2(COMMISSION_PCT,SALARY*COMMISSION_PCT*12,0) AS ILLIK_KOMISSIYA,
       (SALARY*12)+(NVL2(COMMISSION_PCT,SALARY*COMMISSION_PCT*12,0)) AS ILLIK_GELIR
FROM HR.EMPLOYEES;

--TASK9
SELECT E.FIRST_NAME,J.JOB_TITLE,E.SALARY,J.MIN_SALARY,J.MAX_SALARY,
       CASE WHEN SALARY=J.MIN_SALARY THEN 'Minimumda'
       WHEN SALARY=J.MAX_SALARY THEN 'Maksimumda'
       WHEN SALARY<((J.MIN_SALARY+J.MAX_SALARY)/2) THEN 'Asagi yarida'
       ELSE 'Yuxari yarida'
       END AS MOVQE
FROM HR.EMPLOYEES E
JOIN HR.JOBS J
ON E.JOB_ID=J.JOB_ID;
