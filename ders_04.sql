SELECT E.FIRST_NAME,E.LAST_NAME
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M 
ON E.MANAGER_ID=M.EMPLOYEE_ID
WHERE M.FIRST_NAME LIKE 'Steven' AND M.LAST_NAME LIKE 'King';

--TASK5
SELECT E.FIRST_NAME,E.LAST_NAME,E.SALARY,M.FIRST_NAME AS MENECER_ADI,M.SALARY AS MENECER_MAASI
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M
ON E.MANAGER_ID=M.EMPLOYEE_ID
WHERE E.SALARY>M.SALARY;

--TASK6
SELECT E.FIRST_NAME,E.LAST_NAME,E.DEPARTMENT_ID,M.FIRST_NAME AS MENECER_ADI ,M.DEPARTMENT_ID AS MENECER_SOBESI
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M
ON E.MANAGER_ID=M.EMPLOYEE_ID
WHERE E.DEPARTMENT_ID<>M.DEPARTMENT_ID;

--TASK7
SELECT E.FIRST_NAME,E.LAST_NAME,E.JOB_ID,E.SALARY
FROM HR.EMPLOYEES E
WHERE SALARY IN(
SELECT MIN_SALARY FROM HR.JOBS
WHERE MIN_SALARY>=10000)

