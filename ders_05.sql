--TASK1
SELECT FIRST_NAME || ' ' || UPPER(LAST_NAME) AS TAM_AD,SUBSTR(FIRST_NAME,1,1)|| '. '|| LAST_NAME AS QISA_AD,LOWER(EMAIL) || '@company.com' AS EMAIL
FROM HR.EMPLOYEES

--TASK2
SELECT FIRST_NAME,CONCAT(TO_CHAR(SALARY,'FM99,999'),' AZN') AS MAAS,TO_CHAR(SALARY*12,'FM999,999.00') AS ILLIK_MAAS 
FROM HR.EMPLOYEES;
--CUNKI MAAS STRING TIPINDEDIR STRINGDE MUQAYISE ZAMANI ILK REQEM DIGERINDEN BOYUKDURSE O BIRINCI GELIR MESELEN 8000>24000 CUNKI 8>2 STRING TIPINDE OLDUQU ZAMAN

--TASK3
SELECT TO_CHAR(HIRE_DATE,'DD.MM.YYYY') AS ISE_GIRIS,EXTRACT(YEAR FROM HIRE_DATE),TO_CHAR(HIRE_DATE,TRIM('Month')) AS AY_ADI,TO_CHAR(HIRE_DATE,TRIM('Day')) AS HEFTE_GUNU
FROM HR.EMPLOYEES 
ORDER BY HIRE_DATE ASC;

--TASK4
SELECT FIRST_NAME || ' ' || LAST_NAME AS ISCI,TO_CHAR(HIRE_DATE,'DD Month YYYY') AS ISE_GIRIS,TRUNC(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)/12) || ' il ' || MOD(TRUNC(MONTHS_BETWEEN(SYSDATE,HIRE_DATE)),12) || ' ay' AS STAJ
FROM HR.EMPLOYEES

--TASK5 A)
SELECT FIRST_NAME,HIRE_DATE,ADD_MONTHS(HIRE_DATE,3) AS SINAQ_BITIR,LAST_DAY(HIRE_DATE) AS ILK_MAAS_GUNU,LAST_DAY(HIRE_DATE)-HIRE_DATE AS MAASA_QALAN_GUN
FROM HR.EMPLOYEES
--B)
SELECT ADD_MONTHS(TO_DATE('28.02.2025', 'DD.MM.YYYY'), 3) AS yeni_tarix
FROM DUAL
-- CUNKI FEVRAL 28 GUNDEN IBARETDIR VE MAYIN 28 I OLDUQU ZAMAN 3 GUNDE USTUNE GELIR VE 31 MAY OLUR

--TASK6
SELECT CONCAT(FIRST_NAME, ' ', LAST_NAME) || ', komissiya: ' || NVL(TO_CHAR(COMMISSION_PCT,'FM0.00'), 'yoxdur') AS MELUMAT
FROM HR.EMPLOYEES
WHERE TO_CHAR(HIRE_DATE, 'MM') = '03';
--NVL de commission_pct dan sonra yoxdur yaza bilmerik cunki biri integer ve digeri string tipinde olmus olur buda ola bilmez ONA GORE TO_CHARDAN ISTIFADE EDIRIK
--TO_CHAR MM DE CAVAB 03 CIXIR 3 YOX
--o yazilmasi ucun fm funksiyasindan isitfade etdik

--TASK7
SELECT EXTRACT(MONTH FROM HIRE_DATE) AS AY_NO,TO_CHAR(HIRE_DATE,TRIM('Month')) AS AY,COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY AY_NO,AY
ORDER BY AY
--CUNKI ORDER BY AY REQEM OLMADIQI UCUN A DAN BASLIYIB Z YE QEDER GEDIR

SELECT EMPLOYEE_ID FROM HR.EMPLOYEES 

--TASK8
SELECT EMPLOYEE_ID,SUBSTR(LOWER(FIRST_NAME),1,1) || '' || LOWER(LAST_NAME) || LPAD(EMPLOYEE_ID,4,'0') AS LOGIN,REPLACE(PHONE_NUMBER,'.','-') AS TELEFON
FROM HR.EMPLOYEES
WHERE LENGTH(LAST_NAME)>=7
ORDER BY LOGIN

--TASK9
SELECT 
    EXTRACT(YEAR FROM HIRE_DATE) AS IL,
    COUNT(*) AS ISCI_SAYI,
    TO_CHAR(MIN(HIRE_DATE), 'DD.MM.YYYY') AS ILK_TARIX,
    TO_CHAR(MAX(HIRE_DATE), 'DD.MM.YYYY') AS SON_TARIX,
    TO_CHAR(AVG(SALARY), 'FM999,999,990.00') AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY EXTRACT(YEAR FROM HIRE_DATE)
ORDER BY IL ASC;
